def arr(name, data, ctype="u8"):
    lines = []
    for i in range(0, len(data), 32):
        lines.append(",".join(str(v) for v in data[i:i + 32]))
    return f"const {ctype} {name}[{len(data)}] = {{\n" + ",\n".join(lines) + "\n};"


# ------------------------------------------------------------------ fonts
def make_font(cname, path, size):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    h = asc + desc
    glyphs, data = [], []
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(f.getlength(ch)))
        bbox = f.getbbox(ch, anchor="ls")
        left = min(0, bbox[0])
        w = max(adv, bbox[2]) - left + 1
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-left, asc), ch, font=f, fill=255, anchor="ls")
        glyphs.append((w, adv, len(data), left))
        data.extend(img.tobytes())
    c_parts.append(arr(f"{cname}_data", data))
    c_parts.append(f"static const glyph_t {cname}_glyphs[95] = {{" +
                   ",".join(f"{{{w},{a},{o},{l}}}" for w, a, o, l in glyphs) + "};")
    c_parts.append(f"const font_t {cname} = {{{h}, {asc}, {cname}_glyphs, {cname}_data}};\n")
    h_parts.append(f"extern const font_t {cname};")


h_parts += ['typedef struct { u8 w; u8 adv; u32 off; s8 left; } glyph_t;',
            'typedef struct { int h; int base; const glyph_t *g; const u8 *data; } font_t;',
            'typedef struct { int w, h; const u32 *px; } image_t;', '']

make_font("font_ui", INTER + "Inter-Regular.otf", 14)
