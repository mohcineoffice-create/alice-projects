def wallpaper(W, H):
    img = Image.new("RGB", (W, H))
    d = ImageDraw.Draw(img)
    stops = [(0.0, (12, 14, 46)), (0.45, (52, 24, 102)), (0.68, (196, 72, 120)), (0.80, (255, 150, 102)),
             (1.0, (255, 196, 140))]
    for y in range(H):
        t = y / (H - 1)
        for i in range(len(stops) - 1):
            if stops[i][0] <= t <= stops[i + 1][0]:
                u = (t - stops[i][0]) / (stops[i + 1][0] - stops[i][0])
                a, b = stops[i][1], stops[i + 1][1]
                col = tuple(int(a[k] + (b[k] - a[k]) * u) for k in range(3))
                break
        d.line([(0, y), (W, y)], fill=col)
    # sun glow
    glow = Image.new("RGB", (W, H), (0, 0, 0))
    gd = ImageDraw.Draw(glow)
    cx, cy, r = W * .62, H * .66, W * .09
    gd.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(255, 210, 160))
    glow = glow.filter(ImageFilter.GaussianBlur(W * .05))
    img = Image.fromarray if False else img
    from PIL import ImageChops
    img = ImageChops.add(img, glow)
    d = ImageDraw.Draw(img)
    d.ellipse([cx - r * .55, cy - r * .55, cx + r * .55, cy + r * .55], fill=(255, 236, 200))
    # stars
    import random
    rnd = random.Random(7)
    for _ in range(int(W * H / 2500)):
        x, y = rnd.random() * W, rnd.random() * H * .45
        b = rnd.randint(120, 255)
        s = rnd.choice([1, 1, 1, 2])
        d.ellipse([x, y, x + s, y + s], fill=(b, b, min(255, b + 20)))
    # dunes
    layers = [((150, 52, 92), .70, .055, 1.3, .0), ((104, 34, 82), .77, .05, 1.9, 1.7),
              ((66, 22, 64), .85, .045, 2.6, 3.1), ((36, 14, 44), .93, .035, 3.4, .6)]
    for col, base, amp, freq, ph in layers:
        pts = [(0, H)]
        for x in range(0, W + 1, 2):
            t = x / W
            y = H * (base + amp * math.sin(t * math.pi * freq + ph) + amp * .4 * math.sin(t * math.pi * freq * 2.7 + ph * 2))
            pts.append((x, y))
        pts.append((W, H))
        d.polygon(pts, fill=col)
    return img




def vgrad(W, H, stops):
    img = Image.new("RGB", (W, H)); d = ImageDraw.Draw(img)
    for y in range(H):
        t = y / (H - 1)
        for i in range(len(stops) - 1):
            if stops[i][0] <= t <= stops[i + 1][0]:
                u = (t - stops[i][0]) / (stops[i + 1][0] - stops[i][0])
                a, b = stops[i][1], stops[i + 1][1]
                col = tuple(int(a[k] + (b[k] - a[k]) * u) for k in range(3)); break
        d.line([(0, y), (W, y)], fill=col)
    return img


def stars(img, H_frac, n_div, seed):
    import random
    d = ImageDraw.Draw(img); W, H = img.size; rnd = random.Random(seed)
    for _ in range(int(W * H / n_div)):
        x, y = rnd.random() * W, rnd.random() * H * H_frac
        b = rnd.randint(120, 255); sz = rnd.choice([1, 1, 2])
        d.ellipse([x, y, x + sz, y + sz], fill=(b, b, min(255, b + 20)))


def wp_aurora(W, H):
    from PIL import ImageChops
    img = vgrad(W, H, [(0, (3, 8, 24)), (.6, (8, 30, 52)), (1, (10, 40, 60))])
    stars(img, .7, 2200, 3)
    glow = Image.new("RGB", (W, H)); gd = ImageDraw.Draw(glow)
    for col, base, amp, ph, wid in [((40, 255, 160), .30, .07, 0, .05), ((60, 200, 255), .38, .06, 1.8, .04),
                                   ((170, 90, 255), .24, .05, 3.1, .035)]:
        pts = [(x, H * (base + amp * math.sin(x / W * math.pi * 2.2 + ph))) for x in range(0, W + 1, 4)]
        gd.line(pts, fill=col, width=int(H * wid))
    glow = glow.filter(ImageFilter.GaussianBlur(W * .025))
    img = ImageChops.add(img, glow)
    d = ImageDraw.Draw(img)
    for col, base, amp, freq, ph in [((16, 30, 44), .72, .1, 3.2, .3), ((8, 18, 28), .82, .07, 4.4, 1.5)]:
        pts = [(0, H)]
        for x in range(0, W + 1, 3):
            t = x / W
            y = H * (base - amp * abs(math.sin(t * math.pi * freq + ph)) - amp * .3 * math.sin(t * 17 + ph))
            pts.append((x, y))
        pts.append((W, H)); d.polygon(pts, fill=col)
    return img


