def grad(size, top, bottom):
    img = Image.new("RGBA", (size, size))
    d = ImageDraw.Draw(img)
    for y in range(size):
        t = y / (size - 1)
        col = tuple(int(top[i] + (bottom[i] - top[i]) * t) for i in range(3)) + (255,)
        d.line([(0, y), (size, y)], fill=col)
    return img


def squircle(size, top, bottom, radius=0.23):
    base = grad(size, top, bottom)
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, size - 1, size - 1], radius=int(size * radius), fill=255)
    out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    out.paste(base, (0, 0), mask)
    # soft top highlight
    hl = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    hd = ImageDraw.Draw(hl)
    hd.rounded_rectangle([0, 0, size - 1, size // 2], radius=int(size * radius), fill=(255, 255, 255, 28))
    out = Image.alpha_composite(out, Image.composite(hl, Image.new("RGBA", (size, size), (0, 0, 0, 0)), mask))
    return out


def finish(img, size):
    return img.resize((size, size), Image.LANCZOS)


