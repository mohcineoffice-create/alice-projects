def gear(d, cx, cy, r, col, hole_col):
    for k in range(8):
        a = k * math.pi / 4
        pts = []
        for da, rr in [(-0.2, r * 0.8), (-0.13, r * 1.12), (0.13, r * 1.12), (0.2, r * 0.8)]:
            pts.append((cx + rr * math.cos(a + da), cy + rr * math.sin(a + da)))
        d.polygon(pts, fill=col)
    d.ellipse([cx - r * .86, cy - r * .86, cx + r * .86, cy + r * .86], fill=col)
    d.ellipse([cx - r * .38, cy - r * .38, cx + r * .38, cy + r * .38], fill=hole_col)


