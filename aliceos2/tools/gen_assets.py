#!/usr/bin/env python3
"""Generate AliceOS assets as C source: anti-aliased fonts, icons and wallpaper.
Output: src/assets.c and src/assets.h"""
import math, os
from PIL import Image, ImageDraw, ImageFont, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_C = os.path.join(ROOT, "src", "assets.c")
OUT_H = os.path.join(ROOT, "src", "assets.h")
INTER = "/usr/share/fonts/opentype/inter/"
DEJAVU = "/usr/share/fonts/truetype/dejavu/"

c_parts = ['/* Generated by tools/gen_assets.py - do not edit. */', '#include "assets.h"', '']
h_parts = ['/* Generated by tools/gen_assets.py - do not edit. */', '#ifndef ASSETS_H', '#define ASSETS_H',
           '#include "types.h"', '']


def arr(name, data, ctype="u8"):
    lines = []
    for i in range(0, len(data), 32):
        lines.append(",".join(str(v) for v in data[i:i + 32]))
    return f"const {ctype} {name}[{len(data)}] = {{\n" + ",\n".join(lines) + "\n};"


# ------------------------------------------------------------------ fonts
def make_font(cname, path, size):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    h = asc + desc
    glyphs, data = [], []
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(f.getlength(ch)))
        bbox = f.getbbox(ch, anchor="ls")
        left = min(0, bbox[0])
        w = max(adv, bbox[2]) - left + 1
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-left, asc), ch, font=f, fill=255, anchor="ls")
        glyphs.append((w, adv, len(data), left))
        data.extend(img.tobytes())
    c_parts.append(arr(f"{cname}_data", data))
    c_parts.append(f"static const glyph_t {cname}_glyphs[95] = {{" +
                   ",".join(f"{{{w},{a},{o},{l}}}" for w, a, o, l in glyphs) + "};")
    c_parts.append(f"const font_t {cname} = {{{h}, {asc}, {cname}_glyphs, {cname}_data}};\n")
    h_parts.append(f"extern const font_t {cname};")


h_parts += ['typedef struct { u8 w; u8 adv; u32 off; s8 left; } glyph_t;',
            'typedef struct { int h; int base; const glyph_t *g; const u8 *data; } font_t;',
            'typedef struct { int w, h; const u32 *px; } image_t;', '']

make_font("font_ui", INTER + "Inter-Regular.otf", 14)
make_font("font_ui_b", INTER + "Inter-SemiBold.otf", 14)
make_font("font_small", INTER + "Inter-Regular.otf", 12)
make_font("font_title", INTER + "Inter-Bold.otf", 24)
make_font("font_big", INTER + "Inter-Light.otf", 34)
make_font("font_huge", INTER + "InterDisplay-SemiBold.otf", 56)
make_font("font_mono", DEJAVU + "DejaVuSansMono.ttf", 14)


# ------------------------------------------------------------------ icons
S = 4  # supersampling


def grad(size, top, bottom):
    img = Image.new("RGBA", (size, size))
    d = ImageDraw.Draw(img)
    for y in range(size):
        t = y / (size - 1)
        col = tuple(int(top[i] + (bottom[i] - top[i]) * t) for i in range(3)) + (255,)
        d.line([(0, y), (size, y)], fill=col)
    return img


def squircle(size, top, bottom, radius=0.23):
    base = grad(size, top, bottom)
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, size - 1, size - 1], radius=int(size * radius), fill=255)
    out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    out.paste(base, (0, 0), mask)
    # soft top highlight
    hl = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    hd = ImageDraw.Draw(hl)
    hd.rounded_rectangle([0, 0, size - 1, size // 2], radius=int(size * radius), fill=(255, 255, 255, 28))
    out = Image.alpha_composite(out, Image.composite(hl, Image.new("RGBA", (size, size), (0, 0, 0, 0)), mask))
    return out


def finish(img, size):
    return img.resize((size, size), Image.LANCZOS)


def icon_terminal(N):
    img = squircle(N, (58, 63, 80), (24, 26, 34))
    d = ImageDraw.Draw(img)
    f = ImageFont.truetype(DEJAVU + "DejaVuSansMono-Bold.ttf", int(N * 0.42))
    d.text((N * 0.18, N * 0.52), ">_", font=f, fill=(80, 250, 123, 255), anchor="lm")
    for i, c in enumerate([(255, 95, 86), (255, 189, 46), (39, 201, 63)]):
        r = N * 0.045
        cx, cy = N * (0.18 + i * 0.13), N * 0.17
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=c + (255,))
    return img


def icon_calc(N):
    img = squircle(N, (255, 167, 81), (240, 98, 36))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([N * .18, N * .16, N * .82, N * .36], radius=N * .05, fill=(255, 255, 255, 235))
    for r in range(3):
        for c in range(3):
            x, y = N * (.18 + c * .225), N * (.44 + r * .145)
            col = (255, 255, 255, 200) if not (r == 2 and c == 2) else (60, 40, 30, 220)
            d.rounded_rectangle([x, y, x + N * .17, y + N * .11], radius=N * .03, fill=col)
    return img


def icon_notes(N):
    img = squircle(N, (255, 226, 110), (250, 190, 40))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([N * .2, N * .14, N * .8, N * .86], radius=N * .05, fill=(255, 255, 255, 255))
    for i in range(5):
        y = N * (.32 + i * .1)
        d.line([(N * .3, y), (N * (.7 if i < 4 else .55), y)], fill=(150, 160, 175, 255), width=max(1, int(N * .03)))
    d.rectangle([N * .2, N * .14, N * .8, N * .22], fill=(255, 120, 90, 255))
    return img


def icon_paint(N):
    img = squircle(N, (190, 110, 255), (110, 70, 230))
    d = ImageDraw.Draw(img)
    d.ellipse([N * .14, N * .2, N * .86, N * .8], fill=(255, 255, 255, 245))
    d.ellipse([N * .52, N * .55, N * .68, N * .71], fill=(130, 90, 240, 255))  # thumb hole
    for (x, y, c) in [(.3, .38, (255, 82, 82)), (.46, .29, (255, 196, 0)), (.63, .34, (0, 200, 120)),
                      (.28, .56, (33, 150, 243))]:
        r = N * .065
        d.ellipse([N * x - r, N * y - r, N * x + r, N * y + r], fill=c + (255,))
    return img


def icon_snake(N):
    img = squircle(N, (60, 200, 120), (20, 130, 80))
    d = ImageDraw.Draw(img)
    pts = [(.22, .72), (.22, .45), (.5, .45), (.5, .28), (.78, .28)]
    d.line([(N * x, N * y) for x, y in pts], fill=(220, 255, 200, 255), width=int(N * .12), joint="curve")
    r = N * .07
    d.ellipse([N * .78 - r, N * .28 - r, N * .78 + r, N * .28 + r], fill=(220, 255, 200, 255))
    d.ellipse([N * .7 - r, N * .65 - r, N * .7 + r, N * .65 + r], fill=(255, 70, 70, 255))
    return img


def icon_about(N):
    img = squircle(N, (80, 160, 255), (40, 90, 230))
    d = ImageDraw.Draw(img)
    d.ellipse([N * .2, N * .2, N * .8, N * .8], outline=(255, 255, 255, 255), width=int(N * .06))
    f = ImageFont.truetype(INTER + "Inter-Bold.otf", int(N * .4))
    d.text((N * .5, N * .52), "i", font=f, fill=(255, 255, 255, 255), anchor="mm")
    return img


def logo(N):
    """AliceOS logo: gradient circle with a white 'A'."""
    img = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    g = Image.new("RGBA", (N, N))
    gd = ImageDraw.Draw(g)
    for y in range(N):
        t = y / (N - 1)
        a, b = (0, 210, 255), (170, 60, 255)
        gd.line([(0, y), (N, y)], fill=tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3)) + (255,))
    m = Image.new("L", (N, N), 0)
    ImageDraw.Draw(m).ellipse([0, 0, N - 1, N - 1], fill=255)
    img.paste(g, (0, 0), m)
    d = ImageDraw.Draw(img)
    w = N * .085
    d.line([(N * .30, N * .74), (N * .5, N * .24), (N * .70, N * .74)], fill=(255, 255, 255, 255), width=int(w), joint="curve")
    d.line([(N * .38, N * .56), (N * .62, N * .56)], fill=(255, 255, 255, 255), width=int(w))
    return img


def emit_image(cname, img):
    img = img.convert("RGBA")
    px = []
    for r, g, b, a in img.getdata():
        px.append((a << 24) | (r << 16) | (g << 8) | b)
    c_parts.append(arr(f"{cname}_px", px, "u32"))
    c_parts.append(f"const image_t {cname} = {{{img.width}, {img.height}, {cname}_px}};\n")
    h_parts.append(f"extern const image_t {cname};")


for name, fn in [("ic_terminal", icon_terminal), ("ic_calc", icon_calc), ("ic_notes", icon_notes),
                 ("ic_paint", icon_paint), ("ic_snake", icon_snake), ("ic_about", icon_about)]:
    big = fn(48 * S)
    emit_image(name, finish(big, 48))
    emit_image(name + "_s", finish(big, 20))
emit_image("img_logo", finish(logo(64 * S), 64))
emit_image("img_logo_s", finish(logo(22 * S), 22))
emit_image("img_logo_xl", finish(logo(128 * S), 128))


# -------------------------------------------------------------- wallpaper
def wallpaper(W, H):
    img = Image.new("RGB", (W, H))
    d = ImageDraw.Draw(img)
    stops = [(0.0, (12, 14, 46)), (0.45, (52, 24, 102)), (0.68, (196, 72, 120)), (0.80, (255, 150, 102)),
             (1.0, (255, 196, 140))]
    for y in range(H):
        t = y / (H - 1)
        for i in range(len(stops) - 1):
            if stops[i][0] <= t <= stops[i + 1][0]:
                u = (t - stops[i][0]) / (stops[i + 1][0] - stops[i][0])
                a, b = stops[i][1], stops[i + 1][1]
                col = tuple(int(a[k] + (b[k] - a[k]) * u) for k in range(3))
                break
        d.line([(0, y), (W, y)], fill=col)
    # sun glow
    glow = Image.new("RGB", (W, H), (0, 0, 0))
    gd = ImageDraw.Draw(glow)
    cx, cy, r = W * .62, H * .66, W * .09
    gd.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(255, 210, 160))
    glow = glow.filter(ImageFilter.GaussianBlur(W * .05))
    img = Image.fromarray if False else img
    from PIL import ImageChops
    img = ImageChops.add(img, glow)
    d = ImageDraw.Draw(img)
    d.ellipse([cx - r * .55, cy - r * .55, cx + r * .55, cy + r * .55], fill=(255, 236, 200))
    # stars
    import random
    rnd = random.Random(7)
    for _ in range(int(W * H / 2500)):
        x, y = rnd.random() * W, rnd.random() * H * .45
        b = rnd.randint(120, 255)
        s = rnd.choice([1, 1, 1, 2])
        d.ellipse([x, y, x + s, y + s], fill=(b, b, min(255, b + 20)))
    # dunes
    layers = [((150, 52, 92), .70, .055, 1.3, .0), ((104, 34, 82), .77, .05, 1.9, 1.7),
              ((66, 22, 64), .85, .045, 2.6, 3.1), ((36, 14, 44), .93, .035, 3.4, .6)]
    for col, base, amp, freq, ph in layers:
        pts = [(0, H)]
        for x in range(0, W + 1, 2):
            t = x / W
            y = H * (base + amp * math.sin(t * math.pi * freq + ph) + amp * .4 * math.sin(t * math.pi * freq * 2.7 + ph * 2))
            pts.append((x, y))
        pts.append((W, H))
        d.polygon(pts, fill=col)
    return img


wp = wallpaper(1600, 1200).filter(ImageFilter.GaussianBlur(1.2)).resize((400, 300), Image.LANCZOS)
wp.save(os.path.join(ROOT, "tools", "wallpaper_preview.png"))
rgb = []
for r, g, b in wp.getdata():
    rgb.append((r << 16) | (g << 8) | b)
c_parts.append(arr("wallpaper_px", rgb, "u32"))
c_parts.append(f"const image_t img_wallpaper = {{{wp.width}, {wp.height}, wallpaper_px}};\n")
h_parts.append("extern const image_t img_wallpaper;")

h_parts += ['', '#endif']
open(OUT_C, "w").write("\n".join(c_parts) + "\n")
open(OUT_H, "w").write("\n".join(h_parts) + "\n")
print("assets written:", os.path.getsize(OUT_C) // 1024, "KB of C source")
